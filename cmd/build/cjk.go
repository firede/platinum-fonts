package main

import (
	"fmt"
	"text/template"

	"github.com/firede/platinum-fonts/bitmap"
	"github.com/firede/platinum-fonts/internal/bdf"
	"github.com/firede/platinum-fonts/internal/source"
)

// cjkFlavours are the packages of cjk12: the regional forms of one set of
// characters.
var cjkFlavours = []struct {
	Pkg, Flavour, Language string
}{
	{"zhhans", "zh_hans", "Simplified Chinese"},
	{"zhhant", "zh_hant", "Traditional Chinese"},
	{"ja", "ja", "Japanese"},
	{"ko", "ko", "Korean"},
}

// cjkRanges are the blocks of East Asian scripts: what cjk12 takes from
// its source.
var cjkRanges = [][2]rune{
	{0x1100, 0x11FF},   // Hangul Jamo
	{0x2E80, 0x2FDF},   // CJK Radicals Supplement, Kangxi Radicals
	{0x2FF0, 0x2FFF},   // Ideographic Description Characters
	{0x3000, 0x303F},   // CJK Symbols and Punctuation
	{0x3040, 0x30FF},   // Hiragana, Katakana
	{0x3100, 0x312F},   // Bopomofo
	{0x3130, 0x318F},   // Hangul Compatibility Jamo
	{0x3190, 0x31FF},   // Kanbun, Bopomofo Extended, CJK Strokes, Katakana Phonetic Extensions
	{0x3200, 0x33FF},   // Enclosed CJK Letters and Months, CJK Compatibility
	{0x3400, 0x4DBF},   // CJK Unified Ideographs Extension A
	{0x4E00, 0x9FFF},   // CJK Unified Ideographs
	{0xA960, 0xA97F},   // Hangul Jamo Extended-A
	{0xAC00, 0xD7FF},   // Hangul Syllables, Hangul Jamo Extended-B
	{0xF900, 0xFAFF},   // CJK Compatibility Ideographs
	{0xFE10, 0xFE1F},   // Vertical Forms
	{0xFE30, 0xFE4F},   // CJK Compatibility Forms
	{0xFF00, 0xFFEF},   // Halfwidth and Fullwidth Forms
	{0x20000, 0x3FFFF}, // Supplementary and Tertiary Ideographic Planes
}

func inCJK(r rune) bool {
	for _, rg := range cjkRanges {
		if r >= rg[0] && r <= rg[1] {
			return true
		}
	}
	return false
}

// cjkFace is a package of cjk12, made.
type cjkFace struct {
	pkg  string
	face *bitmap.Face
}

// cjkMade is what buildCJK made, for the docs.
type cjkMade struct {
	src     *source.Source
	archive *source.Archive
	faces   []cjkFace
}

func buildCJK(sources map[string]*source.Source, cache string, out map[string][]byte) (*cjkMade, error) {
	src := sources["fusion-pixel-12-proportional"]
	if src == nil {
		return nil, fmt.Errorf("sources.toml has no fusion-pixel-12-proportional")
	}
	data, err := source.Fetch(src, cache)
	if err != nil {
		return nil, err
	}
	archive, err := source.OpenArchive(data)
	if err != nil {
		return nil, err
	}
	made := &cjkMade{src: src, archive: archive}
	for _, fl := range cjkFlavours {
		raw, err := archive.File("fusion-pixel-12px-proportional-" + fl.Flavour + ".bdf")
		if err != nil {
			return nil, err
		}
		font, err := bdf.Parse(raw)
		if err != nil {
			return nil, fmt.Errorf("%s: %v", fl.Flavour, err)
		}
		glyphs := map[rune]bitmap.Glyph{}
		for r, g := range font.Glyphs {
			if inCJK(r) {
				glyphs[r] = g
			}
		}
		packed, err := bitmap.Encode(font.Ascent, font.Descent, glyphs)
		if err != nil {
			return nil, err
		}
		face, err := bitmap.Decode(packed)
		if err != nil {
			return nil, err
		}
		dir := "cjk12/" + fl.Pkg
		out[dir+"/regular.bin"] = packed
		code, err := generate(cjkTemplate, map[string]any{
			"Pkg": fl.Pkg, "Flavour": fl.Flavour, "Language": fl.Language,
			"Version": src.Pinned(), "Glyphs": len(glyphs),
		})
		if err != nil {
			return nil, err
		}
		out[dir+"/"+fl.Pkg+".go"] = code
		made.faces = append(made.faces, cjkFace{fl.Pkg, face})
	}
	return made, nil
}

var cjkTemplate = template.Must(template.New("cjk").Parse(`// Code generated by go run ./cmd/build; DO NOT EDIT.

// Package {{.Pkg}} contains 12px bitmap faces for East Asian scripts,
// {{.Language}} forms, from Fusion Pixel Font {{.Version}} (proportional).
// Styles: Regular, Bold. Bold is Regular emboldened when first used: each
// glyph drawn again a pixel to its right.
// Glyph data: SIL Open Font License 1.1; see NOTICE.md.
package {{.Pkg}}

import (
	_ "embed"
	"sync"

	"github.com/firede/platinum-fonts/bitmap"
)

// Flavour is the Fusion Pixel Font flavour the faces come from.
const Flavour = {{printf "%q" .Flavour}}

// Glyphs is the number of characters each face draws.
const Glyphs = {{.Glyphs}}

//go:embed regular.bin
var dataRegular []byte

var (
	faceRegular = sync.OnceValue(func() *bitmap.Face {
		f, err := bitmap.Decode(dataRegular)
		if err != nil {
			panic(err)
		}
		return f
	})
	faceBold = sync.OnceValue(func() *bitmap.Face {
		f, err := bitmap.Embolden(faceRegular())
		if err != nil {
			panic(err)
		}
		return f
	})
)

// Regular returns the Regular face.
func Regular() *bitmap.Face { return faceRegular() }

// Bold returns the Bold face.
func Bold() *bitmap.Face { return faceBold() }
`))
