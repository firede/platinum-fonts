const ownCopyright = "Copyright (c) 2026, Firede (https://github.com/firede)."

func buildDocs(latin []latinFace, cjk *cjkMade, mono *monoMade, out map[string][]byte) error {
	// Coverage of the national character sets.
	var b strings.Builder
	b.WriteString("# Coverage\n\nCharacters of each national set drawn by the packages of `cjk12`.\n")
	b.WriteString("Generated by `go run ./cmd/build`; do not edit.\n\n| Set |")
	for _, f := range cjk.faces {
		fmt.Fprintf(&b, " `%s` |", f.pkg)
	}
	b.WriteString("\n|---|" + strings.Repeat("---:|", len(cjk.faces)) + "\n")
	for _, set := range coverage.Sets() {
		fmt.Fprintf(&b, "| %s (%d) |", set.Name, len(set.Runes))
		for _, f := range cjk.faces {
			n := set.Count(f.face.Has)
			fmt.Fprintf(&b, " %d (%.1f%%) |", n, 100*float64(n)/float64(len(set.Runes)))
		}
		b.WriteString("\n")
	}
	b.WriteString("| All glyphs |")
	for _, f := range cjk.faces {
		fmt.Fprintf(&b, " %d |", f.face.Len())
	}
	b.WriteString("\n")
	out["docs/coverage.md"] = []byte(b.String())

	pic, err := specimen(latin, cjk, mono)
	if err != nil {
		return err
	}
	out["docs/specimen.png"] = pic

	// Licenses and the notice crediting them.
	var notice strings.Builder
	var ligHolders []string
	for _, line := range strings.Split(string(out[monoLigatureLicense]), "\n") {
		if line = strings.TrimSpace(line); strings.HasPrefix(strings.ToLower(line), "copyright") {
			ligHolders = append(ligHolders, line)
		}
	}
	if len(ligHolders) == 0 {
		return fmt.Errorf("%s has no copyright", monoLigatureLicense)
	}
	var sets strings.Builder
	for _, set := range iconSets {
		var files []string
		for _, name := range set.sources {
			f := licenseFile(name)
			files = append(files, fmt.Sprintf("[%s](%s)", f, f))
		}
		fmt.Fprintf(&sets, "| [%s](%s) | %s | %s |\n", set.name, set.url, set.license, strings.Join(files, ", "))
	}
	nerdLicense := licenseFile(mono.icons.src.Name)
	fmt.Fprintf(&notice, noticeHead, ownCopyright, mono.src.Repository, mono.src.Pinned(), ownCopyright,
		mono.ligSrc.Repository, mono.ligSrc.Commit, monoLigatureLicense, monoLigatureLicense, strings.Join(ligHolders, "; "),
		mono.icons.src.Repository, mono.icons.src.Pinned(), iconsDrawn, iconsDrawn, nerdLicense, nerdLicense, sets.String(),
		cjk.src.Repository, cjk.src.Pinned())
	var ofl strings.Builder
	ofl.WriteString("Platinum Fonts\nhttps://github.com/firede/platinum-fonts\n\n" + ownCopyright + "\n")
	for _, l := range licenses {
		text, err := cjk.archive.File(l.from)
		if err != nil {
			return err
		}
		out[l.to] = text
		head, _, ok := cutLicense(string(text))
		if !ok {
			return fmt.Errorf("%s has no license text", l.from)
		}
		var holders []string
		for _, line := range strings.Split(head, "\n") {
			if line = strings.TrimSpace(line); strings.HasPrefix(strings.ToLower(line), "copyright") {
				holders = append(holders, line)
				ofl.WriteString(line + "\n")
			}
		}
		fmt.Fprintf(&notice, "- [%s](%s), [%s](%s): %s\n", l.font, l.url, l.to, l.to, strings.Join(holders, "; "))
	}
	out["NOTICE.md"] = []byte(notice.String())
	fusion, err := cjk.archive.File("OFL.txt")
	if err != nil {
		return err
	}
	_, body, ok := cutLicense(string(fusion))
	if !ok {
		return fmt.Errorf("the Fusion Pixel archive's OFL.txt has no license text")
	}
	ofl.WriteString("\n" + body)
	out["OFL.txt"] = []byte(ofl.String())
	return nil
}

// cutLicense cuts the text of a font's license where its license text
// starts, after the copyright statements.
func cutLicense(text string) (head, body string, ok bool) {
	i := strings.Index(strings.ToLower(text), "this font software is licensed")
	if i < 0 {
		return "", "", false
	}
	return text[:i], text[i:], true
}

// scaled is an image drawn on in blocks of scale×scale pixels.
type scaled struct {
	*image.RGBA
	scale int
}

func (s scaled) Set(x, y int, c color.Color) {
	for dy := range s.scale {
		for dx := range s.scale {
			s.RGBA.Set(x*s.scale+dx, y*s.scale+dy, c)
		}
	}
}

