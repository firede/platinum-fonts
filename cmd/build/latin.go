package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"text/template"

	"github.com/firede/platinum-fonts/bitmap"
	"github.com/firede/platinum-fonts/internal/drawn"
)

// A family is a package of Latin faces drawn in glyphs/, one per style.
type family struct {
	Pkg, Name, About string
	Styles           []style
}

type style struct {
	Name, File string
	Src        string // the drawing in glyphs/
	Embolden   bool   // the drawing emboldened, by bitmap.EmboldenGlyph
}

var families = []family{
	{
		Pkg: "sans", Name: "Platinum Sans",
		About: "a proportional Latin face: cell 12px, ascent 9, cap height 9, x-height 6",
		Styles: []style{
			{Name: "Regular", File: "regular.bin", Src: "glyphs/sans-regular.txt"},
			{Name: "Bold", File: "bold.bin", Src: "glyphs/sans-bold.txt"},
		},
	},
	{
		Pkg: "sanssmall", Name: "Platinum Sans Small",
		About: "a proportional Latin face: cell 11px, ascent 8, cap height 8, x-height 5",
		Styles: []style{
			{Name: "Regular", File: "regular.bin", Src: "glyphs/sans-small.txt"},
			{Name: "Bold", File: "bold.bin", Src: "glyphs/sans-small.txt", Embolden: true},
		},
	},
}

// latinFace is a style of a family, made.
type latinFace struct {
	family, style string
	face          *bitmap.Face
}

func buildLatin(out map[string][]byte) ([]latinFace, error) {
	var made []latinFace
	for _, fam := range families {
		for _, st := range fam.Styles {
			src, err := os.ReadFile(st.Src)
			if err != nil {
				return nil, err
			}
			f, err := drawn.Parse(st.Src, string(src))
			if err != nil {
				return nil, err
			}
			glyphs := f.Glyphs
			if st.Embolden {
				glyphs = map[rune]bitmap.Glyph{}
				for r, g := range f.Glyphs {
					glyphs[r] = bitmap.EmboldenGlyph(g)
				}
			}
			data, err := bitmap.Encode(f.Ascent, f.Height-f.Ascent, glyphs)
			if err != nil {
				return nil, fmt.Errorf("%s: %v", st.Src, err)
			}
			face, err := bitmap.Decode(data)
			if err != nil {
				return nil, err
			}
			out[fam.Pkg+"/"+st.File] = data
			made = append(made, latinFace{fam.Name, st.Name, face})
		}
		code, err := generate(familyTemplate, fam)
		if err != nil {
			return nil, err
		}
		out[fam.Pkg+"/"+fam.Pkg+".go"] = code
	}
	return made, nil
}

// generate executes t with data and formats the Go source it makes.
func generate(t *template.Template, data any) ([]byte, error) {
	var b bytes.Buffer
	if err := t.Execute(&b, data); err != nil {
		return nil, err
	}
	return format.Source(b.Bytes())
}

var familyTemplate = template.Must(template.New("family").Parse(`// Code generated by go run ./cmd/build; DO NOT EDIT.

// Package {{.Pkg}} contains {{.Name}}, {{.About}}. Styles:
{{- range $i, $s := .Styles}}{{if $i}},{{end}} {{$s.Name}}{{end}}.
{{- range .Styles}}{{if .Embolden}}
// {{.Name}} is Regular emboldened: each glyph drawn again a pixel to its
// right.{{end}}{{end}}
// Glyph data: SIL Open Font License 1.1; see NOTICE.md.
package {{.Pkg}}

import (
	_ "embed"
	"sync"

	"github.com/firede/platinum-fonts/bitmap"
)
{{range .Styles}}
//go:embed {{.File}}
var data{{.Name}} []byte

var face{{.Name}} = sync.OnceValue(func() *bitmap.Face { return decode(data{{.Name}}) })

// {{.Name}} returns {{$.Name}} {{.Name}}.
func {{.Name}}() *bitmap.Face { return face{{.Name}}() }
{{end}}
func decode(data []byte) *bitmap.Face {
	f, err := bitmap.Decode(data)
	if err != nil {
		panic(err)
	}
	return f
}
`))
